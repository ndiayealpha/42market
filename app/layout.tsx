import type { Metadata } from "next";
import { Bricolage_Grotesque, DM_Sans, Geist_Mono } from "next/font/google";
import "../src/styles/globals.scss";

import { AuthApiProvider, SessionProvider } from "@/src/features/auth";
import { defaultAuthClient, getCurrentUser } from "@/src/features/auth/server";
import { QueryProvider } from "@/src/providers/query-provider";
import { ToastProvider } from "@/src/providers/toast-provider";

// A1 (2026-11-17 UAT): DM Sans for body/buttons/inputs, Bricolage Grotesque for every h1.
const dmSans = DM_Sans({
  variable: "--font-dm-sans",
  subsets: ["latin"],
});

const bricolageGrotesque = Bricolage_Grotesque({
  variable: "--font-bricolage-grotesque",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default async function RootLayout({ children }: LayoutProps<"/">) {
  const user = await getCurrentUser();

  return (
    <html
      lang="en"
      className={`${dmSans.variable} ${bricolageGrotesque.variable} ${geistMono.variable} h-full antialiased`}
    >
      <body className="min-h-screen flex flex-col">
        <QueryProvider>
          <ToastProvider>
            <AuthApiProvider>
              <SessionProvider initialUser={user} authClient={defaultAuthClient}>
                {children}
              </SessionProvider>
            </AuthApiProvider>
          </ToastProvider>
        </QueryProvider>
      </body>
    </html>
  );
}
